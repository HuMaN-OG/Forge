const express = require('express');
const router = express.Router();
const fs = require('node:fs');
const path = require('node:path');
const config = require('../config');
const { taskRepository } = require('../db/repositories');

router.get('/', (req, res, next) => {
  try {
    const canonicalWorkspace = path.resolve(config.workspace.path);
    const tasks = taskRepository.list();
    const recordedFiles = [];
    const seenPaths = new Set();

    // 1. Collect from task artifacts
    for (const t of tasks) {
      if (Array.isArray(t.artifacts)) {
        for (const art of t.artifacts) {
          if (art.path && !seenPaths.has(art.path)) {
            seenPaths.add(art.path);
            const exists = fs.existsSync(art.path);
            const stat = exists ? fs.statSync(art.path) : null;
            const ext = path.extname(art.name || art.path).replace('.', '').toLowerCase();

            recordedFiles.push({
              id: `file-${recordedFiles.length + 1}`,
              taskId: t.id,
              name: art.name || path.basename(art.path),
              path: path.resolve(art.path),
              extension: ext,
              type: art.type || ext,
              size: stat ? stat.size : (art.size || 0),
              createdAt: t.completedAt || t.createdAt,
              isAvailableLocally: exists,
              description: `Generated by task #${t.id}: ${t.title}`
            });
          }
        }
      }
    }

    // 2. Also discover any existing files in canonical workspace
    if (fs.existsSync(canonicalWorkspace)) {
      const dirEntries = fs.readdirSync(canonicalWorkspace);
      for (const entry of dirEntries) {
        const fullPath = path.resolve(canonicalWorkspace, entry);
        if (!seenPaths.has(fullPath) && fs.statSync(fullPath).isFile()) {
          seenPaths.add(fullPath);
          const stat = fs.statSync(fullPath);
          const ext = path.extname(entry).replace('.', '').toLowerCase();

          recordedFiles.push({
            id: `file-${recordedFiles.length + 1}`,
            taskId: 'direct_workspace',
            name: entry,
            path: fullPath,
            extension: ext,
            type: ext,
            size: stat.size,
            createdAt: stat.birthtime.toISOString(),
            isAvailableLocally: true,
            description: `Workspace file located in canonical sandbox`
          });
        }
      }
    }

    let filtered = recordedFiles;
    if (req.query.extension && req.query.extension !== 'all') {
      filtered = filtered.filter(f => f.extension.toLowerCase() === req.query.extension.toLowerCase());
    }
    if (req.query.search) {
      const q = req.query.search.toLowerCase();
      filtered = filtered.filter(f =>
        f.name.toLowerCase().includes(q) ||
        f.description.toLowerCase().includes(q)
      );
    }

    return res.json(filtered);
  } catch (err) {
    next(err);
  }
});

router.get('/:id/download', (req, res, next) => {
  try {
    const canonicalWorkspace = path.resolve(config.workspace.path);
    const targetId = req.params.id;

    // Check direct file match in workspace
    const directCandidate = path.resolve(canonicalWorkspace, targetId);
    if (directCandidate.startsWith(canonicalWorkspace) && fs.existsSync(directCandidate) && fs.statSync(directCandidate).isFile()) {
      return res.download(directCandidate, targetId);
    }

    // Check task artifacts
    const tasks = taskRepository.list();
    let fileIdx = 0;
    for (const t of tasks) {
      if (Array.isArray(t.artifacts)) {
        for (const art of t.artifacts) {
          fileIdx++;
          const fileId = `file-${fileIdx}`;
          if (art.path && fs.existsSync(art.path)) {
            const resolved = path.resolve(art.path);
            const basename = path.basename(resolved);
            if (
              targetId === fileId ||
              targetId === basename ||
              targetId === art.name
            ) {
              if (!resolved.startsWith(canonicalWorkspace)) {
                return res.status(403).json({ success: false, error: 'Access denied: File outside workspace sandbox.' });
              }
              return res.download(resolved, art.name || basename);
            }
          }
        }
      }
    }

    return res.status(404).json({ success: false, error: 'File not found on disk in workspace sandbox' });
  } catch (err) {
    next(err);
  }
});

module.exports = router;
