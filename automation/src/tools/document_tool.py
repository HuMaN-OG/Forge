def create_docx_document(
    filename: str,
    title: str,
    content: str,
    sections: Optional[List[Dict[str, str]]],
    workspace_dir: Path,
    overwrite: bool = True
) -> Dict[str, Any]:
    """Generates a verified Microsoft Word (.docx) document."""
    if not DOCX_AVAILABLE:
        return {"success": False, "error": "python-docx is not installed in the python environment."}

    target_path = safe_resolve_path(filename, workspace_dir)
    if not target_path.name.lower().endswith(".docx"):
        target_path = target_path.with_suffix(".docx")

    if target_path.exists() and not overwrite:
        target_path = get_collision_safe_path(target_path)

    target_path.parent.mkdir(parents=True, exist_ok=True)

    doc = docx.Document()

    # Document Title
    h1 = doc.add_heading(title or "FORGE AI Generated Document", level=0)
    h1.style.font.color.rgb = RGBColor(14, 165, 233)  # Sky blue accent

    # Executive Summary / Intro
    if content:
        doc.add_paragraph(content)

    # Structured sections if provided
    if sections and isinstance(sections, list):
        for sec in sections:
            sec_title = sec.get("heading") or sec.get("title") or "Section"
            sec_body = sec.get("body") or sec.get("content") or ""
            doc.add_heading(sec_title, level=1)
            doc.add_paragraph(sec_body)
    elif not content:
        # Default professional body if none provided
        doc.add_heading("1. Executive Summary", level=1)
        doc.add_paragraph(
            f"This document was autonomously generated and verified by FORGE AI Computer Control Engine on {filename}."
        )

    # Footer note
    footer = doc.sections[0].footer
    footer_para = footer.paragraphs[0]
    footer_para.text = "Generated by FORGE AI — Local-First Sandboxed Workspace"

    doc.save(str(target_path))

    file_size = target_path.stat().st_size
    rel_str = str(target_path.relative_to(workspace_dir.resolve()))

    return {
        "success": True,
        "action": "create_docx",
        "file": target_path.name,
        "path": str(target_path),
        "relativePath": rel_str,
        "size": file_size,
        "format": "docx",
        "verified": target_path.exists() and file_size > 0,
        "artifacts": [{
            "name": target_path.name,
            "path": str(target_path),
            "type": "docx",
            "size": file_size
        }]
    }


def create_pdf_document(
    filename: str,
    title: str,
    content: str,
    sections: Optional[List[Dict[str, str]]],
    workspace_dir: Path,
    overwrite: bool = True
) -> Dict[str, Any]:
    """Generates a verified Adobe PDF (.pdf) document using ReportLab."""
    if not REPORTLAB_AVAILABLE:
        return {"success": False, "error": "reportlab is not installed in the python environment."}

    target_path = safe_resolve_path(filename, workspace_dir)
    if not target_path.name.lower().endswith(".pdf"):
        target_path = target_path.with_suffix(".pdf")

    if target_path.exists() and not overwrite:
        target_path = get_collision_safe_path(target_path)

    target_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(target_path),
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'ForgeTitle',
        parent=styles['Heading1'],
        fontSize=22,
        leading=26,
        textColor=colors.HexColor('#0EA5E9'),
        spaceAfter=14
    )
    heading_style = ParagraphStyle(
        'ForgeH2',
        parent=styles['Heading2'],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#1E293B'),
        spaceBefore=12,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'ForgeBody',
        parent=styles['Normal'],
        fontSize=10,
        leading=15,
        textColor=colors.HexColor('#334155'),
        spaceAfter=8
    )

    story = []
    story.append(Paragraph(title or "FORGE AI Document", title_style))
    story.append(Spacer(1, 10))

    if content:
        for para in content.split("\n\n"):
            if para.strip():
                story.append(Paragraph(para.strip().replace("\n", "<br/>"), body_style))
                story.append(Spacer(1, 6))

    if sections and isinstance(sections, list):
        for sec in sections:
            sec_title = sec.get("heading") or sec.get("title") or "Section"
            sec_body = sec.get("body") or sec.get("content") or ""
            story.append(Paragraph(sec_title, heading_style))
            story.append(Paragraph(sec_body.replace("\n", "<br/>"), body_style))
            story.append(Spacer(1, 6))

    doc.build(story)

    file_size = target_path.stat().st_size
    rel_str = str(target_path.relative_to(workspace_dir.resolve()))

    return {
        "success": True,
        "action": "create_pdf",
        "file": target_path.name,
        "path": str(target_path),
        "relativePath": rel_str,
        "size": file_size,
        "format": "pdf",
        "verified": target_path.exists() and file_size > 0,
        "artifacts": [{
            "name": target_path.name,
            "path": str(target_path),
            "type": "pdf",
            "size": file_size
        }]
    }


def create_pptx_presentation(
    filename: str,
    title: str,
    subtitle: str,
    slides: Optional[List[Dict[str, Any]]],
    workspace_dir: Path,
    overwrite: bool = True
) -> Dict[str, Any]:
    """Generates a verified Microsoft PowerPoint (.pptx) presentation."""
    if not PPTX_AVAILABLE:
        return {"success": False, "error": "python-pptx is not installed in the python environment."}

    target_path = safe_resolve_path(filename, workspace_dir)
    if not target_path.name.lower().endswith(".pptx"):
        target_path = target_path.with_suffix(".pptx")

    if target_path.exists() and not overwrite:
        target_path = get_collision_safe_path(target_path)

    target_path.parent.mkdir(parents=True, exist_ok=True)

    prs = Presentation()

    # Slide 1: Title slide layout
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title or "FORGE AI Presentation"
    slide.placeholders[1].text = subtitle or "Autonomous Computer-Use Engine"

    # Additional slides
    if slides and isinstance(slides, list):
        bullet_layout = prs.slide_layouts[1]
        for s in slides:
            s_title = s.get("title") or s.get("heading") or "Slide"
            s_bullets = s.get("bullets") or s.get("points") or [s.get("content", "")]
            c_slide = prs.slides.add_slide(bullet_layout)
            c_slide.shapes.title.text = s_title
            tf = c_slide.placeholders[1].text_frame
            for idx, pt in enumerate(s_bullets):
                if idx == 0:
                    tf.text = str(pt)
                else:
                    p = tf.add_paragraph()
                    p.text = str(pt)
    else:
        # Default overview slide
        bullet_layout = prs.slide_layouts[1]
        c_slide = prs.slides.add_slide(bullet_layout)
        c_slide.shapes.title.text = "Overview"
        tf = c_slide.placeholders[1].text_frame
        tf.text = "Generated autonomously in local sandboxed environment."
        p2 = tf.add_paragraph()
        p2.text = "Zero external cloud telemetry required."
        p3 = tf.add_paragraph()
        p3.text = "Verified on disk and logged in SQLite."

    prs.save(str(target_path))

    file_size = target_path.stat().st_size
    rel_str = str(target_path.relative_to(workspace_dir.resolve()))

    return {
        "success": True,
        "action": "create_pptx",
        "file": target_path.name,
        "path": str(target_path),
        "relativePath": rel_str,
        "size": file_size,
        "format": "pptx",
        "verified": target_path.exists() and file_size > 0,
        "artifacts": [{
            "name": target_path.name,
            "path": str(target_path),
            "type": "pptx",
            "size": file_size
        }]
    }


