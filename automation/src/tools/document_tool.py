def read_pdf_file(filename: str, workspace_dir: Path) -> Dict[str, Any]:
    """Reads and extracts text from a PDF document in the workspace."""
    if not PYPDF_AVAILABLE:
        return {"success": False, "error": "pypdf is not installed in the python environment."}

    target_path = safe_resolve_path(filename, workspace_dir)
    if not target_path.exists():
        return {"success": False, "error": f"PDF file does not exist: {filename}"}

    reader = PdfReader(str(target_path))
    pages_text = []
    for idx, page in enumerate(reader.pages):
        text = page.extract_text() or ""
        pages_text.append(f"--- Page {idx + 1} ---\n{text}")

    full_text = "\n\n".join(pages_text)
    return {
        "success": True,
        "action": "read_pdf",
        "file": target_path.name,
        "pageCount": len(reader.pages),
        "size": target_path.stat().st_size,
        "content": full_text
    }


def read_docx_file(filename: str, workspace_dir: Path) -> Dict[str, Any]:
    """Reads and extracts text from a DOCX document in the workspace."""
    if not DOCX_AVAILABLE:
        return {"success": False, "error": "python-docx is not installed in the python environment."}

    target_path = safe_resolve_path(filename, workspace_dir)
    if not target_path.exists():
        return {"success": False, "error": f"DOCX file does not exist: {filename}"}

    doc = docx.Document(str(target_path))
    paras = [p.text for p in doc.paragraphs if p.text.strip()]
    full_text = "\n\n".join(paras)

    return {
        "success": True,
        "action": "read_docx",
        "file": target_path.name,
        "paragraphCount": len(paras),
        "size": target_path.stat().st_size,
        "content": full_text
    }


def execute_document_tool(params: Dict[str, Any], workspace_dir: Path) -> Dict[str, Any]:
    """
    Main dispatcher for multi-format document operations.
    Supported actions:
    - create_docx
    - create_pdf
    - create_pptx
    - create_csv
    - create_json
    - read_pdf
    - read_docx
    """
    action = params.get("action", "create_docx")

    try:
        if action == "create_docx":
            filename = params.get("filePath") or params.get("filename") or params.get("targetFile") or "Document.docx"
            title = params.get("title") or "FORGE AI Document"
            content = params.get("content") or params.get("text") or ""
            sections = params.get("sections")
            overwrite = bool(params.get("overwrite", True))
            return create_docx_document(filename, title, content, sections, workspace_dir, overwrite)

        elif action == "create_pdf":
            filename = params.get("filePath") or params.get("filename") or params.get("targetFile") or "Document.pdf"
            title = params.get("title") or "FORGE AI Document"
            content = params.get("content") or params.get("text") or ""
            sections = params.get("sections")
            overwrite = bool(params.get("overwrite", True))
            return create_pdf_document(filename, title, content, sections, workspace_dir, overwrite)

        elif action == "create_pptx":
            filename = params.get("filePath") or params.get("filename") or params.get("targetFile") or "Presentation.pptx"
            title = params.get("title") or "Presentation Title"
            subtitle = params.get("subtitle") or "Created with FORGE AI"
            slides = params.get("slides")
            overwrite = bool(params.get("overwrite", True))
            return create_pptx_presentation(filename, title, subtitle, slides, workspace_dir, overwrite)

        elif action == "create_csv":
            filename = params.get("filePath") or params.get("filename") or params.get("targetFile") or "Data.csv"
            headers = params.get("headers") or []
            rows = params.get("rows") or []
            overwrite = bool(params.get("overwrite", True))
            return create_csv_file(filename, headers, rows, workspace_dir, overwrite)

        elif action == "create_json":
            filename = params.get("filePath") or params.get("filename") or params.get("targetFile") or "data.json"
            data = params.get("data") if params.get("data") is not None else {"created": True, "service": "FORGE AI"}
            overwrite = bool(params.get("overwrite", True))
            return create_json_file(filename, data, workspace_dir, overwrite)

        elif action == "read_pdf":
            filename = params.get("targetFile") or params.get("filePath") or params.get("filename")
            return read_pdf_file(filename, workspace_dir)

        elif action == "read_docx":
            filename = params.get("targetFile") or params.get("filePath") or params.get("filename")
            return read_docx_file(filename, workspace_dir)

        else:
            return {
                "success": False,
                "error": f"Unknown document tool action: '{action}'. Permitted actions: ['create_docx', 'create_pdf', 'create_pptx', 'create_csv', 'create_json', 'read_pdf', 'read_docx']"
            }

    except Exception as e:
        return {"success": False, "action": action, "error": str(e)}

